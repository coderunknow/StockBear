#!/usr/bin/env python3
"""Generate a deterministic random-opening suite for engine matches.

The hand-written suite in ``benchmarks/positions/openings.txt`` is small (31
lines). At a fixed node budget the engine is deterministic, so a paired
colour-reversed match over a small suite can produce the *same* score in every
pair, which leaves the pentanomial with zero variance and makes the match
statistically uninformative. A larger suite of short, playable, randomly drawn
openings gives the pairing something to vary over.

Every line is drawn from a fixed seed, so the suite is reproducible; the script
refuses to emit lines that are already decided (a check on the final move, a
material imbalance beyond a minor piece, or a repetition), because those turn the
match into a test of opening selection rather than of the engines.

Usage:
    python3 scripts/make_openings.py --count 240 --plies 8 \
        --out benchmarks/positions/openings_dev4.txt
"""
from __future__ import annotations

import argparse
import random
from pathlib import Path

import chess

# Legal, sensible first moves. A purely uniform first move would spend most of
# the suite on 1.h3 and 1.Na3-type positions, which says little about playing
# strength at normal time controls.
FIRST_MOVES = ["e2e4", "d2d4", "c2c4", "g1f3", "e2e3", "d2d3", "g2g3", "b2b3",
               "f2f4", "b1c3", "b2b4", "g1h3"]

VALUE = {chess.PAWN: 100, chess.KNIGHT: 320, chess.BISHOP: 330,
         chess.ROOK: 500, chess.QUEEN: 900}


def material(board: chess.Board) -> int:
    total = 0
    for square, piece in board.piece_map().items():
        value = VALUE.get(piece.piece_type, 0)
        total += value if piece.color == chess.WHITE else -value
    return total


def draw(rng: random.Random, plies: int) -> list[str]:
    while True:
        board = chess.Board()
        moves: list[str] = []
        seen = {board.fen()}
        ok = True
        for ply in range(plies):
            if ply == 0:
                candidates = [m for m in (chess.Move.from_uci(u) for u in FIRST_MOVES)
                              if m in board.legal_moves]
            else:
                candidates = list(board.legal_moves)
            if not candidates:
                ok = False
                break
            move = rng.choice(candidates)
            board.push(move)
            moves.append(move.uci())
            key = board.fen()
            if key in seen:
                ok = False
                break
            seen.add(key)
        if not ok:
            continue
        if board.is_check():
            continue
        if abs(material(board)) > 200:
            continue
        return moves


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--count", type=int, default=240)
    parser.add_argument("--plies", type=int, default=8)
    parser.add_argument("--seed", type=int, default=20261101)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    rng = random.Random(args.seed)
    lines = [
        "# Random-opening suite for dev4 matches, generated by",
        f"# scripts/make_openings.py --count {args.count} --plies {args.plies} --seed {args.seed}",
        "# Format: <name> | <space separated UCI moves from the start position>.",
        "# Each line is played twice per match with colours reversed.",
    ]
    seen: set[str] = set()
    while len(seen) < args.count:
        moves = draw(rng, args.plies)
        key = " ".join(moves)
        if key in seen:
            continue
        seen.add(key)
        lines.append(f"Random {len(seen):03d} | {key}")
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(seen)} openings to {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
