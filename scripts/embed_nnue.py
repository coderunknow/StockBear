#!/usr/bin/env python3
"""Embed a trained ``.nnue`` file into the engine binary.

Usage:
    python3 scripts/embed_nnue.py --net path/to/net.nnue \
        --out src/evaluation/nnue_net_data.cpp
    python3 scripts/embed_nnue.py --empty --out src/evaluation/nnue_net_data.cpp

The output is a C++ translation unit defining
``stockbear::nnue::kEmbeddedNetSize`` and ``stockbear::nnue::kEmbeddedNetData``.
The bytes are emitted as chunked string literals rather than a brace-initialised
array: compilers parse long string literals quickly and without the per-element
overhead that makes multi-megabyte initialiser lists slow (and, on MSVC,
practically impossible).

The embedded blob is the *serialised* network, byte for byte the same data as the
file, so the loader exercises exactly the same validation path as
``setoption name NnueFile``; the generated header records the SHA-256 so the
provenance of a shipped binary can be checked without unpacking it.
"""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path

CHUNK = 4096


def emit_empty(out: Path) -> None:
    out.write_text(
        "// Generated by scripts/embed_nnue.py - do not edit by hand.\n"
        "// Source: (none)\n"
        f"// SHA-256: {hashlib.sha256(b'').hexdigest()}\n"
        "// Bytes: 0\n"
        '#include "evaluation/nnue_embedded.hpp"\n'
        "\n"
        "namespace stockbear::nnue {\n"
        "\n"
        "namespace {\n"
        "// No trained network is embedded in this build.\n"
        'const std::uint8_t kEmpty[1] = {0};\n'
        "} // namespace\n"
        "\n"
        "const std::size_t kEmbeddedNetSize = 0;\n"
        "const std::uint8_t* const kEmbeddedNetData = kEmpty;\n"
        "} // namespace stockbear::nnue\n"
    )


def escape(block: bytes) -> str:
    # Hex escapes are unambiguous and avoid every quoting problem; printable
    # ASCII is kept as-is so the generated file stays diffable at a glance.
    pieces = []
    for byte in block:
        if byte == 0x22:  # double quote
            pieces.append('\\"')
        elif byte == 0x5C:  # backslash
            pieces.append("\\\\")
        elif 0x20 <= byte < 0x7F:
            pieces.append(chr(byte))
        else:
            pieces.append(f"\\{byte:03o}")
    return "".join(pieces)


def emit_net(net: Path, out: Path) -> None:
    data = net.read_bytes()
    if not data:
        raise SystemExit(f"{net}: empty file")
    digest = hashlib.sha256(data).hexdigest()
    chunks = [data[i : i + CHUNK] for i in range(0, len(data), CHUNK)]
    lines = [
        "// Generated by scripts/embed_nnue.py - do not edit by hand.",
        f"// Source: {net.as_posix()}",
        f"// SHA-256: {digest}",
        f"// Bytes: {len(data)}",
        '#include "evaluation/nnue_embedded.hpp"',
        "",
        "namespace stockbear::nnue {",
        "",
        "namespace {",
        "// The serialised network, split into chunks because a single string literal",
        "// has an implementation-defined length limit.",
    ]
    for index, chunk in enumerate(chunks):
        lines.append(f'const char kNetChunk{index}[] = "{escape(chunk)}";')
    lines.append("const char* const kNetChunks[] = {")
    for index in range(len(chunks)):
        lines.append(f"    kNetChunk{index},")
    lines.append("};")
    lines.append("const std::size_t kNetChunkSizes[] = {")
    for chunk in chunks:
        lines.append(f"    {len(chunk)},")
    lines.append("};")
    lines.append("} // namespace")
    lines.append("")
    lines.append("const std::size_t kEmbeddedNetSize = " + str(len(data)) + ";")
    lines.append("")
    lines.append("namespace {")
    lines.append("// Reassembled once on first use; the loader keeps its own copy of the")
    lines.append("// parsed weights, so this buffer exists only to give the parser one")
    lines.append("// contiguous block.")
    lines.append("const std::uint8_t* assembled() {")
    lines.append("    static std::uint8_t buffer[" + str(len(data)) + "];")
    lines.append("    static bool ready = false;")
    lines.append("    if (!ready) {")
    lines.append("        std::size_t offset = 0;")
    lines.append("        for (std::size_t c = 0; c < sizeof(kNetChunks) / sizeof(kNetChunks[0]); ++c)")
    lines.append("            for (std::size_t i = 0; i < kNetChunkSizes[c]; ++i)")
    lines.append("                buffer[offset++] = static_cast<std::uint8_t>(kNetChunks[c][i]);")
    lines.append("        ready = true;")
    lines.append("    }")
    lines.append("    return buffer;")
    lines.append("}")
    lines.append("} // namespace")
    lines.append("")
    lines.append("const std::uint8_t* const kEmbeddedNetData = assembled();")
    lines.append("} // namespace stockbear::nnue")
    lines.append("")
    out.write_text("\n".join(lines))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--net", type=Path, help="serialised .nnue file to embed")
    parser.add_argument("--out", type=Path, required=True, help="generated .cpp path")
    parser.add_argument("--empty", action="store_true", help="emit the no-network stub")
    args = parser.parse_args()
    if args.empty == bool(args.net):
        parser.error("pass exactly one of --net or --empty")
    args.out.parent.mkdir(parents=True, exist_ok=True)
    if args.empty:
        emit_empty(args.out)
    else:
        emit_net(args.net, args.out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
